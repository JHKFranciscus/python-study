print("--- 반복 변수만 변경 ---")

numbers = [10, 20, 30]

for number in numbers:
    number = number * 2

print(numbers)

# 예상 결과:
# 20
# 40
# 60
# 실제 결과:
# [10, 20, 30]
# 예상과 실제가 다른 이유:
# number에는 두 배가 된 값이 차례로 대입되지만, print(numbers)는 반복 변수가 아니라 원본 리스트 전체를 출력한다.
# 반복 변수만 다시 대입했으므로 원본 리스트는 변경되지 않았다.

print("--- 인덱스로 원본 수정 ---")

for index in range(len(numbers)):
    numbers[index] = numbers[index] * 2

print(numbers)

# 예상 결과:
# [20, 40, 60]
# 실제 결과:
# [20, 40, 60]


