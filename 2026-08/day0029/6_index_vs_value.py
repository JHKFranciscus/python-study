# 인덱스 순회: 값이 저장된 위치가 필요할 때 사용
# 값 중심 순회: 각 값만 읽거나 계산할 때 사용
# enumerate() 순회: 위치와 값이 모두 필요할 때 사용

scores = [70, 85, 60]

print("--- 인덱스 순회 ---")

for index in range(len(scores)):
    print(index, scores[index])

# 예상 결과:
# 0 70
# 1 85
# 2 60
# 실제 결과:
# 0 70
# 1 85
# 2 60

# index가 의미하는 것: 리스트의 첫번째 요소로부터 떨어져 있는 위치
# scores[index]가 의미하는 것: socres 리스트에서 index위치에 있는 요소의 값


print()
print("--- 값 중심 순회 ---")

for score in scores:
    print(score)

# 예상 결과:
# 70
# 85
# 60
# 실제 결과:
# 70
# 85
# 60

# 이 반복문 안에서 현재 score의 위치 번호를 바로 알 수 있는가:
# 이 반복문은 iterable에서 요소를 하나씩 꺼내는 것이기 때문에 score의 위치 번호를 바로 알 수 없다.


print()
print("--- 위치와 값 함께 순회 ---")

for index, score in enumerate(scores):
    print(index, score)

# 예상 결과:
# 0 70
# 1 85
# 2 60
# 실제 결과:
# 0 70
# 1 85
# 2 60


