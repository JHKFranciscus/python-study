class Product:
    def __init__(self, name, price):
        self.name = name
        self.price = price

    def print_info(self):
        print(f"name: {self.name}, price: {self.price}")

product = Product("키보드", 50000)

print("=== 생성 직후 ===")
product.print_info()

print("=== 문자열 가격 직접 대입 ===")
product.price = "오만원"
product.print_info()

print("=== 음수 가격 직접 대입 ===")
product.price = -5000
product.print_info()

print("=== 존재하지 않던 속성 추가 ===")
product.discount_rate = 20
print(product.discount_rate)

